-- OPERATIONAL_PLANS: الخطة التشغيلية السنوية لجهة تنظيمية، مشتقة من خطة استراتيجية
-- أو من خطة تشغيلية لجهة أعلى مباشرة (وليس من الجذر دائماً - القسم 4)
CREATE TABLE operational_plans (
    op_plan_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategic_plan_id        NUMBER       NOT NULL,
    strategic_plan_version   NUMBER(6)    NOT NULL,
    org_unit_id               NUMBER      NOT NULL,
    academic_year             VARCHAR2(9) NOT NULL,
    parent_op_plan_id         NUMBER,
    status                    VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    created_by                NUMBER,
    created_at                 TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by                 NUMBER,
    updated_at                 TIMESTAMP,
    is_active                  NUMBER(1)   DEFAULT 1 NOT NULL,
    deleted_at                  TIMESTAMP,
    CONSTRAINT uq_op_plans_unit_year UNIQUE (strategic_plan_id, org_unit_id, academic_year),
    CONSTRAINT fk_op_plans_strat_plan FOREIGN KEY (strategic_plan_id) REFERENCES strategic_plans (plan_id),
    CONSTRAINT fk_op_plans_org_unit FOREIGN KEY (org_unit_id) REFERENCES org_units (org_unit_id),
    CONSTRAINT fk_op_plans_parent FOREIGN KEY (parent_op_plan_id) REFERENCES operational_plans (op_plan_id),
    CONSTRAINT ck_op_plans_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED')),
    CONSTRAINT ck_op_plans_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE operational_plans IS 'الخطة التشغيلية السنوية لجهة تنظيمية، مشتقة هرمياً من جهة أعلى مباشرة';
COMMENT ON COLUMN operational_plans.strategic_plan_version IS 'يُثبّت إصدار الخطة الاستراتيجية الموروث وقت الاشتقاق (AD-01) - لا يتغير لاحقاً';
COMMENT ON COLUMN operational_plans.parent_op_plan_id IS 'الخطة الأعلى المشرفة مباشرة التي اشتُقت منها هذه الخطة (self FK)، NULL لخطة رئاسة الجامعة';

CREATE INDEX ix_op_plans_org_unit ON operational_plans (org_unit_id);
CREATE INDEX ix_op_plans_academic_year ON operational_plans (academic_year);
CREATE INDEX ix_op_plans_parent ON operational_plans (parent_op_plan_id);
CREATE INDEX ix_op_plans_strat_plan ON operational_plans (strategic_plan_id);

-- OP_PLAN_ITEMS: العناصر الموروثة (مرجعية للقراءة) + الحقول التشغيلية القابلة للتعديل
CREATE TABLE op_plan_items (
    item_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
