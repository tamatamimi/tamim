-- 1. الهيكل التنظيمي والمستخدمون (القسم 3.1)
--------------------------------------------------------------------------------

-- ORG_UNITS: الوحدات التنظيمية للجامعة على شكل شجرة (رئاسة/عمادة/كلية/قسم/فرع...)
CREATE TABLE org_units (
    org_unit_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id       NUMBER,
    unit_type       VARCHAR2(30)  NOT NULL,
    name_ar         VARCHAR2(200) NOT NULL,
    name_en         VARCHAR2(200),
    level_no        NUMBER(3),
    created_by      NUMBER,
    created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by      NUMBER,
    updated_at      TIMESTAMP,
    is_active       NUMBER(1)     DEFAULT 1 NOT NULL,
    deleted_at      TIMESTAMP,
    CONSTRAINT fk_org_units_parent FOREIGN KEY (parent_id) REFERENCES org_units (org_unit_id),
    CONSTRAINT ck_org_units_type CHECK (unit_type IN
        ('PRESIDENCY', 'VP_OFFICE', 'COLLEGE', 'DEANSHIP', 'DEPARTMENT', 'BRANCH', 'ADMIN')),
    CONSTRAINT ck_org_units_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE org_units IS 'الوحدات التنظيمية للجامعة (شجرة هرمية) - الجذر (رئاسة الجامعة) بدون parent_id';
COMMENT ON COLUMN org_units.parent_id IS 'FK ذاتي، NULL للجذر (رئاسة الجامعة)';
COMMENT ON COLUMN org_units.level_no IS 'عمق الوحدة في الشجرة، لأغراض الاستعلام السريع';

CREATE INDEX ix_org_units_parent ON org_units (parent_id);

-- USERS: مستخدمو النظام، كل مستخدم مرتبط بجهة تنظيمية واحدة
CREATE TABLE users (
    user_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR2(100) NOT NULL,
    full_name       VARCHAR2(200) NOT NULL,
    email           VARCHAR2(200),
    job_title       VARCHAR2(200),
    org_unit_id     NUMBER        NOT NULL,
    status          VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
    created_by      NUMBER,
    created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by      NUMBER,
    updated_at      TIMESTAMP,
    is_active       NUMBER(1)     DEFAULT 1 NOT NULL,
    deleted_at      TIMESTAMP,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT fk_users_org_unit FOREIGN KEY (org_unit_id) REFERENCES org_units (org_unit_id),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_users_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE users IS 'مستخدمو النظام';
COMMENT ON COLUMN users.org_unit_id IS 'جهة المستخدم التنظيمية';

CREATE INDEX ix_users_org_unit ON users (org_unit_id);

--------------------------------------------------------------------------------
-- 1.1 نموذج RBAC مرن (القسم 6.1): USERS -> USER_ROLES -> ROLES -> ROLE_PERMISSIONS -> PERMISSIONS
--------------------------------------------------------------------------------

-- ROLES: الأدوار الأساسية (SYS_ADMIN, UNIT_MANAGER, DATA_ENTRY, REVIEWER, VIEWER)
CREATE TABLE roles (
    role_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code       VARCHAR2(30)  NOT NULL,
    name_ar         VARCHAR2(200) NOT NULL,
    name_en         VARCHAR2(200),
    created_by      NUMBER,
    created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by      NUMBER,
    updated_at      TIMESTAMP,
    is_active       NUMBER(1)     DEFAULT 1 NOT NULL,
    deleted_at      TIMESTAMP,
    CONSTRAINT uq_roles_code UNIQUE (role_code),
    CONSTRAINT ck_roles_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE roles IS 'الأدوار الأساسية في النظام';

-- PERMISSIONS: الصلاحيات الذرية (مثل VIEW_REPORT, EDIT_DATA, APPROVE_PLAN)
CREATE TABLE permissions (
    permission_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code VARCHAR2(50)  NOT NULL,
    name_ar         VARCHAR2(200) NOT NULL,
    name_en         VARCHAR2(200),
    created_by      NUMBER,
    created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by      NUMBER,
    updated_at      TIMESTAMP,
    is_active       NUMBER(1)     DEFAULT 1 NOT NULL,
    deleted_at      TIMESTAMP,
    CONSTRAINT uq_permissions_code UNIQUE (permission_code),
    CONSTRAINT ck_permissions_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE permissions IS 'الصلاحيات الذرية لتخصيص مرن يتجاوز الأدوار الثابتة';

-- USER_ROLES: ربط المستخدمين بالأدوار (m:n)
CREATE TABLE user_roles (
    user_id         NUMBER NOT NULL,
    role_id         NUMBER NOT NULL,
    created_by      NUMBER,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (role_id)
);
COMMENT ON TABLE user_roles IS 'ربط المستخدمين بالأدوار';

CREATE INDEX ix_user_roles_role ON user_roles (role_id);

-- ROLE_PERMISSIONS: ربط الأدوار بالصلاحيات (m:n)
CREATE TABLE role_permissions (
    role_id         NUMBER NOT NULL,
    permission_id   NUMBER NOT NULL,
    created_by      NUMBER,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_perm_role FOREIGN KEY (role_id) REFERENCES roles (role_id),
    CONSTRAINT fk_role_perm_perm FOREIGN KEY (permission_id) REFERENCES permissions (permission_id)
);
COMMENT ON TABLE role_permissions IS 'ربط الأدوار بالصلاحيات الذرية';

CREATE INDEX ix_role_permissions_perm ON role_permissions (permission_id);

