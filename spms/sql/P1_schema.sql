-- STRATEGIC_PLANS: الخطة الاستراتيجية الخمسية (إصدارات + تأريخ فعّال)
CREATE TABLE strategic_plans (
    plan_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title_ar        VARCHAR2(300) NOT NULL,
    start_year      NUMBER(4)     NOT NULL,
    end_year        NUMBER(4)     NOT NULL,
    status          VARCHAR2(20)  DEFAULT 'DRAFT' NOT NULL,
    version_no      NUMBER(6)     DEFAULT 1 NOT NULL,
    effective_from  DATE,
    created_by      NUMBER,
    created_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by      NUMBER,
    updated_at      TIMESTAMP,
    is_active       NUMBER(1)     DEFAULT 1 NOT NULL,
    deleted_at      TIMESTAMP,
    CONSTRAINT ck_strategic_plans_status CHECK (status IN ('DRAFT', 'APPROVED', 'ARCHIVED')),
    CONSTRAINT ck_strategic_plans_years CHECK (end_year >= start_year),
    CONSTRAINT ck_strategic_plans_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE strategic_plans IS 'الخطة الاستراتيجية الخمسية للجامعة، مثال: الخطة الاستراتيجية الثالثة 2026-2030';
COMMENT ON COLUMN strategic_plans.version_no IS 'رقم الإصدار، يبدأ من 1 (AD-01)';
COMMENT ON COLUMN strategic_plans.effective_from IS 'التاريخ الفعّال لهذا الإصدار (AD-01) - التقارير التاريخية لا تتأثر بتعديل لاحق';

-- DIMENSIONS: أبعاد بطاقة الأداء المتوازن (التعلّم والنمو، العمليات الداخلية، المستفيدون، البُعد المالي)
CREATE TABLE dimensions (
    dimension_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id             NUMBER        NOT NULL,
    name_ar             VARCHAR2(300) NOT NULL,
    name_en             VARCHAR2(300),
    weight_pct          NUMBER(5,2),
    is_weight_explicit  NUMBER(1)     DEFAULT 0 NOT NULL,
    display_order       NUMBER(4),
    created_by          NUMBER,
    created_at          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          NUMBER,
    updated_at          TIMESTAMP,
    is_active           NUMBER(1)     DEFAULT 1 NOT NULL,
    deleted_at           TIMESTAMP,
    CONSTRAINT fk_dimensions_plan FOREIGN KEY (plan_id) REFERENCES strategic_plans (plan_id),
    CONSTRAINT ck_dimensions_weight CHECK (weight_pct IS NULL OR weight_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_dimensions_weight_flag CHECK (is_weight_explicit IN (0, 1)),
    CONSTRAINT ck_dimensions_weight_pair CHECK (is_weight_explicit = 0 OR weight_pct IS NOT NULL),
    CONSTRAINT ck_dimensions_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE dimensions IS 'أبعاد بطاقة الأداء المتوازن ضمن خطة استراتيجية معينة';
COMMENT ON COLUMN dimensions.weight_pct IS 'الوزن النسبي، حقل اختياري (AD-02)';
COMMENT ON COLUMN dimensions.is_weight_explicit IS '0 = وزن ضمني (توزيع متساوٍ - fallback)، 1 = وزن صريح أدخله المستخدم';

CREATE INDEX ix_dimensions_plan ON dimensions (plan_id);

-- STRATEGIC_OBJECTIVES: الأهداف الاستراتيجية (نفس نمط الوزن الاختياري لـ DIMENSIONS)
CREATE TABLE strategic_objectives (
    strategic_objective_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dimension_id            NUMBER        NOT NULL,
    name_ar                 VARCHAR2(300) NOT NULL,
    name_en                 VARCHAR2(300),
    weight_pct               NUMBER(5,2),
    is_weight_explicit       NUMBER(1)     DEFAULT 0 NOT NULL,
    display_order            NUMBER(4),
    created_by               NUMBER,
    created_at                TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by                NUMBER,
    updated_at                TIMESTAMP,
    is_active                 NUMBER(1)    DEFAULT 1 NOT NULL,
    deleted_at                 TIMESTAMP,
    CONSTRAINT fk_strat_obj_dimension FOREIGN KEY (dimension_id) REFERENCES dimensions (dimension_id),
    CONSTRAINT ck_strat_obj_weight CHECK (weight_pct IS NULL OR weight_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_strat_obj_weight_flag CHECK (is_weight_explicit IN (0, 1)),
    CONSTRAINT ck_strat_obj_weight_pair CHECK (is_weight_explicit = 0 OR weight_pct IS NOT NULL),
    CONSTRAINT ck_strat_obj_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE strategic_objectives IS 'الأهداف الاستراتيجية ضمن بُعد معين';

CREATE INDEX ix_strat_obj_dimension ON strategic_objectives (dimension_id);

-- SUB_OBJECTIVES: الأهداف الفرعية
CREATE TABLE sub_objectives (
    sub_objective_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategic_objective_id   NUMBER        NOT NULL,
    name_ar                  VARCHAR2(300) NOT NULL,
    name_en                  VARCHAR2(300),
    display_order            NUMBER(4),
    created_by                NUMBER,
    created_at                 TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by                 NUMBER,
    updated_at                 TIMESTAMP,
    is_active                  NUMBER(1)    DEFAULT 1 NOT NULL,
    deleted_at                  TIMESTAMP,
    CONSTRAINT fk_sub_obj_strat_obj FOREIGN KEY (strategic_objective_id)
        REFERENCES strategic_objectives (strategic_objective_id),
    CONSTRAINT ck_sub_obj_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE sub_objectives IS 'الأهداف الفرعية ضمن هدف استراتيجي معين';

CREATE INDEX ix_sub_obj_strat_obj ON sub_objectives (strategic_objective_id);

-- KPIS: مؤشرات الأداء الرئيسية
CREATE TABLE kpis (
    kpi_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sub_objective_id    NUMBER        NOT NULL,
    code                VARCHAR2(30)  NOT NULL,
    name_ar             VARCHAR2(400) NOT NULL,
    unit_measurement    VARCHAR2(50),
    baseline_value      NUMBER(18,4),
    target_cumulative   NUMBER(18,4),
    weight_pct          NUMBER(5,2),
    is_weight_explicit  NUMBER(1)     DEFAULT 0 NOT NULL,
    display_order       NUMBER(4),
    created_by          NUMBER,
    created_at          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          NUMBER,
    updated_at          TIMESTAMP,
    is_active           NUMBER(1)     DEFAULT 1 NOT NULL,
    deleted_at           TIMESTAMP,
    CONSTRAINT uq_kpis_code UNIQUE (code),
    CONSTRAINT fk_kpis_sub_obj FOREIGN KEY (sub_objective_id) REFERENCES sub_objectives (sub_objective_id),
    CONSTRAINT ck_kpis_weight CHECK (weight_pct IS NULL OR weight_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_kpis_weight_flag CHECK (is_weight_explicit IN (0, 1)),
    CONSTRAINT ck_kpis_weight_pair CHECK (is_weight_explicit = 0 OR weight_pct IS NOT NULL),
    CONSTRAINT ck_kpis_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE kpis IS 'مؤشرات الأداء الرئيسية ضمن هدف فرعي معين';
COMMENT ON COLUMN kpis.code IS 'كود داخلي (مثال: KPI-26-0001) - REQ-012: يُعرض دائماً الاسم لا الكود في الواجهة';
COMMENT ON COLUMN kpis.target_cumulative IS 'المستهدف التراكمي لكل مدة الخطة (خمس سنوات)';

CREATE INDEX ix_kpis_sub_obj ON kpis (sub_objective_id);

-- KPI_YEARLY_TARGETS: التوزيع اليدوي للمستهدفات السنوية (REQ-030) - لا توزيع آلي متساوٍ
CREATE TABLE kpi_yearly_targets (
    target_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kpi_id          NUMBER    NOT NULL,
    target_year     NUMBER(4) NOT NULL,
    value_target    NUMBER(18,4) NOT NULL,
    created_by      NUMBER,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by      NUMBER,
    updated_at      TIMESTAMP,
    is_active       NUMBER(1) DEFAULT 1 NOT NULL,
    deleted_at      TIMESTAMP,
    CONSTRAINT uq_kpi_yearly_targets UNIQUE (kpi_id, target_year),
    CONSTRAINT fk_kpi_yearly_targets_kpi FOREIGN KEY (kpi_id) REFERENCES kpis (kpi_id),
    CONSTRAINT ck_kpi_yearly_targets_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE kpi_yearly_targets IS 'REQ-030: مستهدف سنوي لكل مؤشر، يُدخل يدوياً - لا يوجد توزيع آلي متساوٍ مفروض';

CREATE INDEX ix_kpi_yearly_targets_year ON kpi_yearly_targets (target_year);

-- PROJECTS: المشاريع (مرتبطة بمؤشر أداء)
CREATE TABLE projects (
    project_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kpi_id              NUMBER        NOT NULL,
    name_ar             VARCHAR2(300) NOT NULL,
    description         VARCHAR2(4000),
    responsible_unit_id NUMBER        NOT NULL,
    start_date          DATE,
    end_date            DATE,
    approval_status     VARCHAR2(20)  DEFAULT 'DRAFT' NOT NULL,
    created_by          NUMBER,
    created_at          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          NUMBER,
    updated_at          TIMESTAMP,
    is_active           NUMBER(1)     DEFAULT 1 NOT NULL,
    deleted_at           TIMESTAMP,
    CONSTRAINT fk_projects_kpi FOREIGN KEY (kpi_id) REFERENCES kpis (kpi_id),
    CONSTRAINT fk_projects_unit FOREIGN KEY (responsible_unit_id) REFERENCES org_units (org_unit_id),
    CONSTRAINT ck_projects_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_projects_approval CHECK (approval_status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_projects_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE projects IS 'المشاريع، كل مشروع مرتبط بمؤشر أداء رئيسي واحد';

CREATE INDEX ix_projects_kpi ON projects (kpi_id);
CREATE INDEX ix_projects_unit ON projects (responsible_unit_id);

-- ACTIVITIES: الأنشطة - نقطة إدخال واحدة (REQ-005)، لا تكرار عبر شاشات أخرى
CREATE TABLE activities (
    activity_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id            NUMBER        NOT NULL,
    name_ar               VARCHAR2(300) NOT NULL,
    responsible_unit_id   NUMBER        NOT NULL,
    target_count          NUMBER(10),
    start_date            DATE,
    end_date              DATE,
    created_by            NUMBER,
    created_at            TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by            NUMBER,
    updated_at            TIMESTAMP,
    is_active             NUMBER(1)     DEFAULT 1 NOT NULL,
    deleted_at              TIMESTAMP,
    CONSTRAINT fk_activities_project FOREIGN KEY (project_id) REFERENCES projects (project_id),
    CONSTRAINT fk_activities_unit FOREIGN KEY (responsible_unit_id) REFERENCES org_units (org_unit_id),
    CONSTRAINT ck_activities_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_activities_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE activities IS 'قاعدة: النشاط يُدخل من نافذة واحدة فقط ويُستدعى في بقية الشاشات - لا جدول تكرار (REQ-005)';

CREATE INDEX ix_activities_project ON activities (project_id);
CREATE INDEX ix_activities_unit ON activities (responsible_unit_id);

-- SUPPORTING_UNITS: جدول ربط m:n للجهات المشاركة/المساندة في مشروع أو نشاط
CREATE TABLE supporting_units (
    supporting_unit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type         VARCHAR2(20) NOT NULL,
    entity_id           NUMBER       NOT NULL,
    org_unit_id         NUMBER       NOT NULL,
    created_by          NUMBER,
    created_at          TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    is_active            NUMBER(1)   DEFAULT 1 NOT NULL,
    CONSTRAINT uq_supporting_units UNIQUE (entity_type, entity_id, org_unit_id),
    CONSTRAINT fk_supporting_units_org FOREIGN KEY (org_unit_id) REFERENCES org_units (org_unit_id),
    CONSTRAINT ck_supporting_units_type CHECK (entity_type IN ('PROJECT', 'ACTIVITY')),
    CONSTRAINT ck_supporting_units_active CHECK (is_active IN (0, 1))
);
COMMENT ON TABLE supporting_units IS 'الجهات المساندة/المشاركة في تنفيذ مشروع أو نشاط (m:n متعدد الأنواع)';
COMMENT ON COLUMN supporting_units.entity_type IS 'PROJECT أو ACTIVITY - يحدد الجدول الذي يشير إليه entity_id';

CREATE INDEX ix_supporting_units_entity ON supporting_units (entity_type, entity_id);
CREATE INDEX ix_supporting_units_org ON supporting_units (org_unit_id);

