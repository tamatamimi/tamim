-- AUDIT_LOG: سجل تدقيق لكل العمليات الحساسة في النظام
CREATE TABLE audit_log (
    log_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          NUMBER,
    org_unit_id       NUMBER,
    action_type        VARCHAR2(20) NOT NULL,
    entity_name          VARCHAR2(100) NOT NULL,
    entity_id             NUMBER,
    old_value              CLOB,
    new_value               CLOB,
    action_time               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ip_address                 VARCHAR2(45),
    CONSTRAINT fk_audit_log_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_audit_log_org_unit FOREIGN KEY (org_unit_id) REFERENCES org_units (org_unit_id),
    CONSTRAINT ck_audit_log_action CHECK (action_type IN
        ('CREATE', 'UPDATE', 'APPROVE', 'DELETE', 'LOGIN', 'LOGOUT')),
    CONSTRAINT ck_audit_log_old_json CHECK (old_value IS JSON),
    CONSTRAINT ck_audit_log_new_json CHECK (new_value IS JSON)
);
COMMENT ON TABLE audit_log IS 'سجل تدقيق لكل عملية مسجَّلة (REQ-054) - يُملأ عبر triggers أو من داخل حزم الأعمال';
COMMENT ON COLUMN audit_log.old_value IS 'JSON بصيغة CLOB - القيمة قبل التعديل';
COMMENT ON COLUMN audit_log.new_value IS 'JSON بصيغة CLOB - القيمة بعد التعديل';
COMMENT ON COLUMN audit_log.ip_address IS 'يدعم IPv4/IPv6 كنص';

CREATE INDEX ix_audit_log_user ON audit_log (user_id);
CREATE INDEX ix_audit_log_entity ON audit_log (entity_name, entity_id);
CREATE INDEX ix_audit_log_time ON audit_log (action_time);

