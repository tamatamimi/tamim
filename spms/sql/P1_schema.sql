-- SPMS - نظام إدارة التخطيط الاستراتيجي
-- جامعة العلوم والتكنولوجيا - عدن | إدارة تقنية المعلومات
--
-- Prompt P1 - قاعدة البيانات: مخطط قاعدة البيانات (DDL)
-- استناداً إلى القسم 3 (نموذج البيانات) والقرارات المعمارية في القسم 0
-- من SPMS_Technical_Spec_for_Claude_Code.
--
-- نطاق هذا السكربت (P1 فقط):
--   * كل الجداول بأعمدتها ومفاتيحها الأساسية والأجنبية.
--   * أعمدة التدقيق القياسية على كل جدول جوهري: created_by/at, updated_by/at, is_active.
--   * Soft-delete فقط (AD-06) - لا حذف فيزيائي للكيانات الجوهرية.
--   * ترميز AL32UTF8 - يُضبط عند إنشاء قاعدة البيانات / الـ Pluggable Database
--     (NLS_CHARACTERSET)، وليس داخل هذا السكربت.
--   * فهارس على المفاتيح الأجنبية وأعمدة الاستعلام المتكرر (org_unit_id, academic_year, target_year).
--   * قيود CHECK على الحقول المعدودة (status, unit_type, period_type, ...).
--
-- لا يُنفَّذ أي منطق أعمال هنا (لا حزم PL/SQL، لا Triggers إجرائية) - ذلك في
-- Prompt P2 (PKG_INHERITANCE), Prompt P3 (PKG_CALC + AUDIT_LOG triggers)
-- و Prompt P4 (PKG_SECURITY).
--
-- السكربت قابل للتشغيل مرة واحدة على مخطط (schema) فارغ، بترتيب يحترم
-- تبعيات المفاتيح الأجنبية.
